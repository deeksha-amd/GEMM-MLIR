#!/usr/bin/env python3
"""Emit a VNNI + vdpbf16ps GEMM ukernel for a given register tile / packed layout.

Used to tune bench/prod_bf16_ukernel.mlir.in.  The winning configuration is
frozen into that file; this script is how the sweep in out/bf16_tuning.txt was
produced and how to redo it.

  ./gen_bf16_ukernel.py --mr 8 --nr 32 --b-layout panel --a-layout panel

The generated kernel is the classic outer-product register tile:

  for jb:  for ib:  acc[MR][NR/16] = C tile          (loaded once)
             for k2 in 0..K/2:                        (VNNI pairs)
               b[0..NR/16] = Bpanel                   (NR i32 = NR/16 zmm)
               for r in 0..MR: acc[r][c] = dpbf16ps(acc[r][c], bcast(Ap[r]), b[c])
           store acc

dpbf16ps computes dst[i] += a[2i]*b[2i] + a[2i+1]*b[2i+1] over 16 f32 lanes, so
one i32 lane of the packed arrays holds the (k, k+1) bf16 pair -- that is VNNI.
"""
from __future__ import annotations

import argparse

M, N, K = 128, 4096, 4096
K2 = K // 2  # VNNI pairs

HEADER = """// GENERATED by bench/gen_bf16_ukernel.py -- do not hand-edit.
// VNNI-packed bf16 GEMM ukernel: vpbroadcastd (A pair) + vdpbf16ps (B pair).
// Register tile MR={mr} x NR={nr}.  A layout: {alay}.  B layout: {blay}.
//
// This is the same instruction sequence PACE/libXSMM JITs.  Packing:
//   Ap[m][k2] : i32 = bits(A[m][2*k2]) | bits(A[m][2*k2+1]) << 16
//   Bp[k2][n] : i32 = bits(B[2*k2][n]) | bits(B[2*k2+1][n]) << 16   <- VNNI
// Bitcasting 16 of those i32 gives vector<32xbf16> in exactly the lane order
// dpbf16ps wants.  Like PACE's preprocess(), the pack itself is not timed.
//
// A and B are all bf16 1.0 (0x3F80, a packed pair = 0x3F803F80), so the packed
// arrays are a constant fill: same memory traffic and same instruction stream
// as real packed data, without a pack loop in the benchmark.  Every C element
// must therefore come out to exactly K = 4096 per pass.
//
// NOTE: this file names an ISA on purpose.  It is a layer-3 ukernel
// experiment, NOT the portable shape (see ../DESIGN.md).  In production this
// kernel comes from libXSMM/PACE or tpp-mlir, not hand-written per arch.

func.func private @rtclock() -> f64
func.func private @printF64(f64)
func.func private @printNewline()
"""


def gen(mr: int, nr: int, a_layout: str, b_layout: str, order: str) -> str:
    if nr % 16:
        raise ValueError("NR must be a multiple of the 16 f32 lanes of a zmm")
    if N % nr:
        raise ValueError(f"N={N} not divisible by NR={nr}")
    nvec = nr // 16          # zmm registers per B row slice
    nib, njb = M // mr, N // nr
    rem = M % mr             # leftover rows handled by one narrower tile
    if rem:
        # The A panel layout indexes rows as (tile, k, row-in-tile), which has
        # no name for rows past the last full tile, and with jb inside ib the
        # tail would have to re-walk all of B.  Both are avoidable only with a
        # second packed buffer, which is not what we are measuring here.
        if a_layout == "panel":
            raise ValueError(f"M={M} not divisible by MR={mr}: the remainder "
                             f"tile of {rem} rows needs the flat A layout")
        if order != "jouter":
            raise ValueError(f"M={M} not divisible by MR={mr}: the remainder "
                             "tile needs the jouter loop order")

    a_ty = (f"memref<{nib}x{K2}x{mr}xi32>" if a_layout == "panel"
            else f"memref<{M}x{K2}xi32>")
    b_ty = (f"memref<{njb}x{K2}x{nr}xi32>" if b_layout == "panel"
            else f"memref<{K2}x{N}xi32>")
    c_ty = f"memref<{M}x{N}xf32>"
    sig = f"({a_ty}, {b_ty}, {c_ty})"
    vf32 = "vector<16xf32>"

    L: list[str] = []
    w = L.append

    # index constants the body needs: row offsets, 16-column offsets, tile sizes
    consts = {0, 1, mr, nr}
    consts |= set(range(mr))
    consts |= {c * 16 for c in range(nvec)}

    def emit_tile(sfx: str, rows: int, ind: str) -> None:
        """One MR x NR register tile: load C, run the k loop, store C.

        `sfx` keeps SSA names unique between the main tile and the remainder
        tile; `rows` is the tile height (MR, or the remainder).
        """
        # column c of the tile: c == 0 is the shared tile origin %jv0
        def jvn(c: int) -> str:
            return "%jv0" if c == 0 else f"%jv{sfx}{c}"

        for r in range(1, rows):
            w(f"{ind}%i{sfx}{r} = arith.addi %i{sfx}0, %c{r} : index")
        for c in range(1, nvec):
            w(f"{ind}{jvn(c)} = arith.addi %jv0, %c{c * 16} : index")
        w("")
        # C tile is loaded once here and stored once below, so the k loop
        # carries it in registers instead of a load/store round trip per step.
        for r in range(rows):
            for c in range(nvec):
                w(f"{ind}%acc{sfx}{r}_{c} = vector.load "
                  f"%C[%i{sfx}{r}, {jvn(c)}] : {c_ty}, {vf32}")
        w("")
        accs = [f"%acc{sfx}{r}_{c}" for r in range(rows) for c in range(nvec)]
        iters = [f"%s{sfx}{r}_{c}" for r in range(rows) for c in range(nvec)]
        vtys = ", ".join([vf32] * len(accs))
        w(f"{ind}%r{sfx}:{len(accs)} = scf.for %k{sfx} = %c0 to %cK2 step %c1")
        w(f"{ind}    iter_args(" + ", ".join(f"{s} = {a}" for s, a in
                                             zip(iters, accs)) + ")")
        w(f"{ind}    -> ({vtys}) {{")

        # B: one contiguous vector<16xi32> per 16 columns of the tile.
        for c in range(nvec):
            idx = (f"%jb, %k{sfx}, %c{c * 16}" if b_layout == "panel"
                   else f"%k{sfx}, {jvn(c)}")
            w(f"{ind}  %bi{sfx}{c} = vector.load %Bp[{idx}] "
              f": {b_ty}, vector<16xi32>")
            w(f"{ind}  %b{sfx}{c} = vector.bitcast %bi{sfx}{c} "
              f": vector<16xi32> to vector<32xbf16>")
        w("")
        # A: broadcast one packed (k, k+1) pair per row of the tile.
        for r in range(rows):
            ld = (f"%Ap[%ib, %k{sfx}, %c{r}]" if a_layout == "panel"
                  else f"%Ap[%i{sfx}{r}, %k{sfx}]")
            w(f"{ind}  %d{sfx}{r} = memref.load {ld} : {a_ty}")
            w(f"{ind}  %w{sfx}{r} = vector.broadcast %d{sfx}{r} "
              f": i32 to vector<16xi32>")
            w(f"{ind}  %a{sfx}{r} = vector.bitcast %w{sfx}{r} "
              f": vector<16xi32> to vector<32xbf16>")
            for c in range(nvec):
                w(f"{ind}  %n{sfx}{r}_{c} = llvm.call_intrinsic "
                  f'"llvm.x86.avx512bf16.dpbf16ps.512"'
                  f"(%s{sfx}{r}_{c}, %a{sfx}{r}, %b{sfx}{c})")
                w(f"{ind}      : ({vf32}, vector<32xbf16>, vector<32xbf16>) "
                  f"-> {vf32}")
        w("")
        w(f"{ind}  scf.yield " + ", ".join(f"%n{sfx}{r}_{c}"
                                           for r in range(rows)
                                           for c in range(nvec)))
        w(f"{ind}      : {vtys}")
        w(f"{ind}}}")
        w("")
        for n, (r, c) in enumerate((r, c) for r in range(rows)
                                   for c in range(nvec)):
            w(f"{ind}vector.store %r{sfx}#{n}, %C[%i{sfx}{r}, {jvn(c)}] "
              f": {c_ty}, {vf32}")

    w(HEADER.format(mr=mr, nr=nr, alay=a_layout, blay=b_layout))
    w(f"func.func @gemm(%Ap: {a_ty}, %Bp: {b_ty}, %C: {c_ty}) {{")
    for c in sorted(consts):
        w(f"  %c{c} = arith.constant {c} : index")
    w(f"  %cK2 = arith.constant {K2} : index")
    w(f"  %cNB = arith.constant {njb} : index")
    w(f"  %cMB = arith.constant {nib} : index")
    w("")

    # --- loop nest over register tiles -------------------------------------
    # jouter keeps one packed B panel (K2 x NR i32) hot in L2 while every row
    # block of A sweeps it; iouter instead keeps the A panel hot and re-streams
    # all of B per row block.
    outer, inner = ("jb", "ib") if order == "jouter" else ("ib", "jb")
    bound = {"jb": "%cNB", "ib": "%cMB"}
    w(f"  scf.for %{outer} = %c0 to {bound[outer]} step %c1 {{")
    # %jv0 has to dominate the remainder tile too, so it is computed as soon
    # as %jb exists rather than in the innermost body.
    if order == "jouter":
        w(f"    %jv0 = arith.muli %jb, %c{nr} : index")
    w(f"    scf.for %{inner} = %c0 to {bound[inner]} step %c1 {{")
    if order != "jouter":
        w(f"      %jv0 = arith.muli %jb, %c{nr} : index")
    w(f"      %i0 = arith.muli %ib, %c{mr} : index")
    emit_tile("", mr, "      ")
    w("    }")
    if rem:
        w("")
        w(f"    // remainder: M={M} is not a multiple of MR={mr}")
        w(f"    %it0 = arith.constant {M - rem} : index")
        emit_tile("t", rem, "    ")
    w("  }")
    w("  return")
    w("}")
    w("")

    # --- driver ------------------------------------------------------------
    w("func.func @main() {")
    w("  %c0 = arith.constant 0 : index")
    w("  %c1 = arith.constant 1 : index")
    w("  %reps = arith.constant $REPS : index")
    w("  // 0x3F803F80 = two packed bf16 1.0 values")
    w("  %pair = arith.constant 1065369472 : i32")
    w("  %zf = arith.constant 0.0 : f32")
    w("")
    w(f"  %Ap = memref.alloc() : {a_ty}")
    w(f"  %Bp = memref.alloc() : {b_ty}")
    w(f"  %C = memref.alloc() : {c_ty}")
    w(f"  linalg.fill ins(%pair : i32) outs(%Ap : {a_ty})")
    w(f"  linalg.fill ins(%pair : i32) outs(%Bp : {b_ty})")
    w(f"  linalg.fill ins(%zf : f32) outs(%C : {c_ty})")
    w("")
    w("  // Warmup: page faults and first touch land here, not in the timed")
    w("  // region.  It also adds one K to C, which the checksum accounts for.")
    w(f"  func.call @gemm(%Ap, %Bp, %C) : {sig} -> ()")
    w("")
    w("  %t0 = func.call @rtclock() : () -> f64")
    w("  scf.for %r = %c0 to %reps step %c1 {")
    w(f"    func.call @gemm(%Ap, %Bp, %C) : {sig} -> ()")
    w("  }")
    w("  %t1 = func.call @rtclock() : () -> f64")
    w("")
    w("  %dt = arith.subf %t1, %t0 : f64")
    w("  func.call @printF64(%dt) : (f64) -> ()")
    w("  func.call @printNewline() : () -> ()")
    w("")
    w("  // Checksum: C accumulates, so after warmup + $REPS passes every")
    w(f"  // element is K * (1 + $REPS) = {K} * (1 + $REPS).")
    w(f"  %v = memref.load %C[%c0, %c0] : {c_ty}")
    w("  %vf = arith.extf %v : f32 to f64")
    w("  func.call @printF64(%vf) : (f64) -> ()")
    w("  func.call @printNewline() : () -> ()")
    w("")
    w("  // ...and C[0][0] alone would not notice a bad remainder tile or a")
    w("  // mis-indexed column, so count every element that is not K*(1+reps).")
    w("  %rp1 = arith.addi %reps, %c1 : index")
    w("  %rpi = arith.index_cast %rp1 : index to i32")
    w("  %rpf = arith.sitofp %rpi : i32 to f32")
    w(f"  %kf = arith.constant {float(K)} : f32")
    w("  %exp = arith.mulf %rpf, %kf : f32")
    w(f"  %cM = arith.constant {M} : index")
    w(f"  %cN = arith.constant {N} : index")
    w("  %bad = scf.for %ii = %c0 to %cM step %c1 "
      "iter_args(%o = %c0) -> (index) {")
    w("    %brow = scf.for %jj = %c0 to %cN step %c1 "
      "iter_args(%p = %o) -> (index) {")
    w(f"      %cv = memref.load %C[%ii, %jj] : {c_ty}")
    w("      %ne = arith.cmpf one, %cv, %exp : f32")
    w("      %inc = arith.select %ne, %c1, %c0 : index")
    w("      %nx = arith.addi %p, %inc : index")
    w("      scf.yield %nx : index")
    w("    }")
    w("    scf.yield %brow : index")
    w("  }")
    w("  %badi = arith.index_cast %bad : index to i64")
    w("  %badf = arith.sitofp %badi : i64 to f64")
    w("  func.call @printF64(%badf) : (f64) -> ()")
    w("  func.call @printNewline() : () -> ()")
    w("")
    w(f"  memref.dealloc %Ap : {a_ty}")
    w(f"  memref.dealloc %Bp : {b_ty}")
    w(f"  memref.dealloc %C : {c_ty}")
    w("  return")
    w("}")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mr", type=int, default=8)
    ap.add_argument("--nr", type=int, default=32)
    ap.add_argument("--a-layout", choices=["flat", "panel"], default="panel")
    ap.add_argument("--b-layout", choices=["flat", "panel"], default="panel")
    ap.add_argument("--order", choices=["jouter", "iouter"], default="jouter")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    text = gen(a.mr, a.nr, a.a_layout, a.b_layout, a.order)
    if a.out:
        with open(a.out, "w") as f:
            f.write(text)
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
